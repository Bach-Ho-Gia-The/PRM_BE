package com.structure.springboot.features.product.entity;

import com.structure.springboot.infrastructure.persistence.BaseEntity;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.SuperBuilder;

/** Một ảnh gallery: URL được trả cho frontend, public ID chỉ dùng nội bộ để dọn file do backend upload. */
@Entity
@Table(
        name = "product_images",
        // Nạp gallery của một sản phẩm là lọc theo product_id rồi sắp theo sort_order.
        indexes = @Index(name = "idx_product_images_product_id", columnList = "product_id, sort_order")
)
@Getter
@Setter
@SuperBuilder
@AllArgsConstructor
@NoArgsConstructor
public class ProductImageEntity extends BaseEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "product_id", nullable = false)
    private ProductEntity product;

    @Column(name = "image_url", nullable = false, length = 500)
    private String imageUrl;

    /** Null for older seed/external URLs; generated by the server for new uploads. */
    @Column(name = "public_id", length = 500)
    private String publicId;

    /** Thứ tự hiển thị trong gallery. Nhỏ hơn đứng trước; trùng số thì thứ tự không đảm bảo. */
    @Column(name = "sort_order", nullable = false)
    private Integer sortOrder;
}
